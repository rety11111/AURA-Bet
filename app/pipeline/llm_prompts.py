OUTPUT_CONTRACT = """ОТВЕТ — строго один JSON-объект (никаких пояснений и markdown):
{
  "prob_home": float,            // 0..1
  "prob_draw": float | null,     // null для видов без ничьей (баскетбол, теннис, киберспорт, MMA)
  "prob_away": float,            // 0..1, сумма трёх = 1.0 ± 0.02
  "expected_total": float,       // ожидаемый тотал матча (голы/очки/раунды/сеты)
  "total_sigma": float,          // обычно 0.8–3.5 для футбола/хоккея, 10–18 для баскетбола
  "expected_margin": float,      // ожидаемая разница: хозяева − гости (знак важен!)
  "margin_sigma": float,         // сигма разницы
  "confidence": float,           // 0..1
  "data_quality": "ok" | "weak",
  "key_factors": ["...", "..."], // 2–5 конкретных факторов, на которых построен прогноз
  "risk_notes": ["...", "..."]   // 1–4 риска: чего не хватает, что может сломать прогноз
}"""


def analyzer_system(sport: str) -> str:
    checklist = CHECKLISTS.get(sport, "ЧЕК-ЛИСТ: общие принципы — форма, составы, мотивация, календарь.")
    return f"{_BASE_ANALYZER}\n{checklist}\n\n{OUTPUT_CONTRACT}"


def _fmt_list(items: list[Any], empty: str = "нет данных") -> str:
    if not items:
        return empty
    return "\n".join(f"  - {item}" for item in items[:12])


def build_analyzer_user_prompt(context: dict[str, Any]) -> str:
    """Сериализует контекст матча в текст для аналитика.

    Контекст собирается в pipeline/analyzer.py и содержит всё, что есть по матчу:
    команды, лигу, кэфы, форму, травмы, составы, H2H, плотность календаря,
    стат-модель, активные league_insights и (для лайва) игровую ситуацию.
    """
    match = context.get("match", {})
    lines: list[str] = [
        f"МАТЧ: {match.get('home_team')} — {match.get('away_team')}",
        f"Спорт: {match.get('sport')} | Лига: {match.get('league')}"
        + (f" (tier: {match.get('league_tier')})" if match.get("league_tier") else ""),
        f"Старт (UTC): {match.get('starts_at')}",
        f"Статус: {match.get('status')}" + (f" | Стадия: {match.get('live_stage')}" if match.get("live_stage") else ""),
        "",
        "КОЭФЫ (лучшая цена из агрегатора, implied — без маржи):",
        _fmt_list(context.get("odds_lines"), "нет кэфов"),
    ]
    if context.get("stat_model"):
        lines += ["", "СТАТ-МОДЕЛЬ (справочно, можно спорить с объяснением):", json.dumps(context["stat_model"], ensure_ascii=False, indent=1)]
    if context.get("form"):
        lines += ["", "ФОРМА (последние матчи):", json.dumps(context["form"], ensure_ascii=False, indent=1)[:2500]]
    if context.get("injuries"):
        lines += ["", "ТРАВМЫ/ПОТЕРИ:", _fmt_list(context["injuries"])]
    if context.get("lineups"):
        lines += ["", "СОСТАВЫ/ВРАТАРИ:", json.dumps(context["lineups"], ensure_ascii=False, indent=1)[:1500]]
    if context.get("h2h"):
        lines += ["", "H2H:", json.dumps(context["h2h"], ensure_ascii=False, indent=1)[:1500]]
    if context.get("schedule_density"):
        lines += ["", "ПЛОТНОСТЬ КАЛЕНДАРЯ:", json.dumps(context["schedule_density"], ensure_ascii=False, indent=1)]
    if context.get("news"):
        lines += ["", "НОВОСТИ (RSS, проверь достоверность):", _fmt_list(context["news"])]
    if context.get("live_info"):
        lines += ["", "ЛАЙВ-СИТУАЦИЯ:", json.dumps(context["live_info"], ensure_ascii=False, indent=1)[:2000]]
    if context.get("league_insights"):
        lines += [
            "",
            "ИСТОРИЧЕСКИЕ УРОКИ ПО ЭТОЙ ЛИГЕ (сгенерированы по прошлым сигналам — учитывай):",
            json.dumps(context["league_insights"], ensure_ascii=False, indent=1)[:1500],
        ]
    lines += ["", "Верни JSON строго по контракту."]
    return "\n".join(lines)


