"""Промпты всех уровней LLM-каскада (Модуль 4).

Здесь собраны:
  * SCREENER_SYSTEM + промпт уровня 1 (дешёвый отсев);
  * ANALYZER_SYSTEM_BY_SPORT — чек-листы по каждому виду спорта (Ур.2);
  * OUTPUT_CONTRACT — строгий JSON-контракт аналитика (единый для всех спортов);
  * JUDGE_SYSTEM / JUDGE_LIVE_SYSTEM — системные промпты финального арбитра (Ур.3);
  * SELF_REVIEW_SYSTEM — недельный self-review лиги (Модуль 8);
  * сборщики пользовательских промптов: они сериализуют контекст матча в текст,
    который реально видит модель.

Принципы, которые заложены в формулировки:
  * «не выдумывай данные»: если чего-то нет в контексте, модель обязана сказать это
    в risk_notes, а не фантазировать;
  * LLM может спорить со стат-моделью, но обязана объяснить, почему;
  * арбитр не перепрогнозирует с нуля, а ищет ошибки данных/системные переоценки.
"""

from __future__ import annotations

import json
from typing import Any

# --------------------------------------------------------------------------- #
# Ур.1 — скринер
# --------------------------------------------------------------------------- #
SCREENER_SYSTEM = """Ты — быстрый скринер ставок. Твоя работа — за 1 проход отсеять матчи, \
где искать value бессмысленно, и оставить те, где стоит потратить время аналитика.

Считай skip, если:
- нет внятной мотивации (товарищеский матч, резервные составы, ничего не решается);
- очевидно, что линия «пустая» (нет информации, которая может дать перевес);
- данные о командах противоречивы/устарели настолько, что анализ бессмысленен;
- матч относится к лиге/турниру вне нашего фокуса.

Считай pass, если есть хотя бы одна содержательная зацепка: заметная разница формы, \
травмы ключевых игроков, плотный календарь, ротация, возврат после перерыва, \
явное расхождение между кэфом и очевидной силой команд.

Отвечай ТОЛЬКО JSON без пояснений:
{"verdict": "pass" | "skip", "reason": "одна короткая строка"}

Не пересказывай данные. Не используй markdown. Не добавляй поля."""


def build_screener_user_prompt(summary: dict[str, Any]) -> str:
    return (
        "Сводка матча (JSON):\n"
        f"{json.dumps(summary, ensure_ascii=False, indent=1)}\n\n"
        "Верни JSON с verdict и reason."
    )


